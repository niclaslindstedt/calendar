/** Juhannuspäivä: the Saturday falling 20–26 June. */
function juhannuspaiva(year: number): { month: number; day: number } {
  return weekdayOnOrAfter(year, 6, 20, 6);
}

/** Pyhäinpäivä: the Saturday falling 31 October – 6 November. */
function pyhainpaiva(year: number): { month: number; day: number } {
  return weekdayOnOrAfter(year, 10, 31, 6);
}

/** The day before a computed holiday — how juhannusaatto is expressed. */
function dayBefore(of: (year: number) => { month: number; day: number }) {
  return (year: number) => {
    const day = of(year);
    return addToDate(year, day.month, day.day, -1);
  };
}

