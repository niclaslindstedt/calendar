// The Finnish holidays for a year: the thirteen official pyhäpäivät, plus the
// eves above at their collective default. Juhannuspäivä and pyhäinpäivä are
// both pinned to a Saturday, the way Sweden pins midsommardagen and alla
// helgons dag; everything else is a fixed date or hangs off the computus.
function holidays(year: number): readonly Holiday[] {
  const easter = easterSunday(year);
  const chain = (offset: number, name: string): Holiday => ({
    ...addToDate(year, easter.month, easter.day, offset),
    name,
    red: true,
    off: true,
  });
  return [
    { month: 1, day: 1, name: "Uudenvuodenpäivä", red: true, off: true },
    { month: 1, day: 6, name: "Loppiainen", red: true, off: true },
    chain(-2, "Pitkäperjantai"),
    chain(0, "Pääsiäispäivä"),
    chain(1, "2. pääsiäispäivä"),
    { month: 5, day: 1, name: "Vappu", red: true, off: true },
    chain(39, "Helatorstai"),
    chain(49, "Helluntaipäivä"),
    { ...juhannuspaiva(year), name: "Juhannuspäivä", red: true, off: true },
    { ...pyhainpaiva(year), name: "Pyhäinpäivä", red: true, off: true },
    { month: 12, day: 6, name: "Itsenäisyyspäivä", red: true, off: true },
    { month: 12, day: 25, name: "Joulupäivä", red: true, off: true },
    { month: 12, day: 26, name: "Tapaninpäivä", red: true, off: true },
    ...eveHolidays(EVES, year),
  ];
}

