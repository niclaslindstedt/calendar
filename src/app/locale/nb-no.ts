// The eves Norwegian agreements hand back. Neither is a helligdag: julaften
// is free under most tariffavtaler, and nyttårsaften is worked and finished
// early, which is what `"half"` says.
const EVES: readonly Eve[] = [
  {
    id: "julaften",
    name: "Julaften",
    date: () => ({ month: 12, day: 24 }),
    collective: "off",
  },
  {
    id: "nyttarsaften",
    name: "Nyttårsaften",
    date: () => ({ month: 12, day: 31 }),
    collective: "half",
  },
];

// The Norwegian holidays for a year: the twelve røde dager, plus the eves
// above at their collective default. Note skjærtorsdag — see the header.
function holidays(year: number): readonly Holiday[] {
  const easter = easterSunday(year);
  const chain = (offset: number, name: string): Holiday => ({
    ...addToMonthDay(year, easter.month, easter.day, offset),
    name,
    red: true,
    off: true,
  });
  return [
    { month: 1, day: 1, name: "1. nyttårsdag", red: true, off: true },
    chain(-3, "Skjærtorsdag"),
    chain(-2, "Langfredag"),
    chain(0, "1. påskedag"),
    chain(1, "2. påskedag"),
    { month: 5, day: 1, name: "Offentlig høytidsdag", red: true, off: true },
    { month: 5, day: 17, name: "Grunnlovsdagen", red: true, off: true },
    chain(39, "Kristi himmelfartsdag"),
    chain(49, "1. pinsedag"),
    chain(50, "2. pinsedag"),
    { month: 12, day: 25, name: "1. juledag", red: true, off: true },
    { month: 12, day: 26, name: "2. juledag", red: true, off: true },
    ...eveHolidays(EVES, year),
  ];
}

// Norwegian hyphenation. Close to Swedish — the same Nordic onsets, plus the
// ones Norwegian spells with three letters ("skj", "skr") — and the same
// rule that an ordinary two-consonant run is simply divided: "Mag-nus", not
// "Ma-gnus".
